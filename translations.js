function getCurrentLanguage() {
    return sessionStorage.getItem('language') || 'en';
}

function getCurrentCurrency() {
    return sessionStorage.getItem('currency') || 'RUB';
}

function translate(key) {
    const lang = getCurrentLanguage();
    const keys = key.split('.');
    let localized = translations[lang];
    let fallback = translations.en;

    for (const k of keys) {
        localized = localized && typeof localized === 'object' ? localized[k] : undefined;
        fallback = fallback && typeof fallback === 'object' ? fallback[k] : undefined;
    }

    return localized ?? fallback ?? key;
}

function getPrice(plan) {
    const currency = getCurrentCurrency();
    return prices[currency][plan];
}

function getCurrencySymbol() {
    const currency = getCurrentCurrency();
    return prices[currency].symbol;
}


